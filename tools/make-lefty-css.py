#!/usr/bin/env python3
"""tools/make-lefty-css.py — writes the left-handed mode of the class notes into public/css/appunti.css.

Left-handed mode (html.lefty) mirrors everything that is pushed to the right: rows with "space-between" are reversed,
"margin-left: auto" becomes "margin-right: auto", right-aligned text and "flex-end" go left. Instead of listing the classes by
hand, this script reads the stylesheet, finds every rule that has one of those declarations and writes the mirrored copy
between the LEFTY markers at the end of the file. Run it again after adding rules:   python3 tools/make-lefty-css.py
"""
import re
import sys

PATH = 'public/css/appunti.css'
BEGIN, END = '/* LEFTY:BEGIN (generated by tools/make-lefty-css.py: do not edit by hand) */', '/* LEFTY:END */'
SKIP = ('.code-actions', '.mm-', '.kebab', '.tt-', '.idx-', '.pdf-', '.vbd', '.toast', '.bell-count', '.sr', 'html.lefty')


def split_blocks(css):
    """Top-level (selector, body) pairs of a stylesheet; @media bodies are kept whole."""
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0:
            break
        head = css[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            depth += {'{': 1, '}': -1}.get(css[k], 0)
            k += 1
        out.append((head, css[j + 1:k - 1]))
        i = k
    return out


def mirror(body):
    extra = []
    if re.search(r'justify-content:\s*space-between', body) and 'flex-direction: column' not in body:
        extra.append('flex-direction: row-reverse')
    if re.search(r'margin-left:\s*auto', body):
        extra += ['margin-left: 0', 'margin-right: auto']
    if re.search(r'justify-content:\s*flex-end', body):
        extra.append('justify-content: flex-start')
    if re.search(r'text-align:\s*right', body):
        extra.append('text-align: left')
    return extra


def rules(css, wrapper=None):
    res = []
    for head, body in split_blocks(css):
        if head.startswith('@media'):
            res += rules(body, head)
        elif head.startswith('@') or not head:
            continue
        else:
            sels = [s.strip() for s in head.split(',') if s.strip() and not any(x in s for x in SKIP)]
            extra = mirror(body)
            if sels and extra:
                res.append((wrapper, ', '.join('html.lefty ' + s for s in sels), '; '.join(extra) + ';'))
    return res


def main():
    css = open(PATH, encoding='utf-8').read()
    if BEGIN in css:
        css = css[:css.index(BEGIN)].rstrip() + '\n'
    out = [BEGIN]
    by_wrapper = {}
    for wrapper, sel, decl in rules(re.sub(r'/\*.*?\*/', '', css, flags=re.S)):
        by_wrapper.setdefault(wrapper, []).append(f'{sel} {{ {decl} }}')
    for wrapper in sorted(by_wrapper, key=lambda w: (w is not None, w or '')):
        if wrapper:
            out.append(wrapper + ' {\n' + '\n'.join('    ' + r for r in by_wrapper[wrapper]) + '\n}')
        else:
            out += by_wrapper[wrapper]
    out.append(END)
    open(PATH, 'w', encoding='utf-8').write(css + '\n' + '\n'.join(out) + '\n')
    print(f'{sum(len(v) for v in by_wrapper.values())} mirrored rules written')


if __name__ == '__main__':
    sys.exit(main())
