#!/usr/bin/env python3
"""Builds public/js/botola-q-en.js and botola-q-it.js from two JSON files with the same questions in the same order:
   python3 tools/build-botola-q.py en.json it.json
Each item: [difficulty 0|1|2, question, right answer, 3 wrong answers]. Source of the questions: Open Trivia DB (CC BY-SA 4.0)."""
import json, sys
en, it = (json.load(open(f)) for f in sys.argv[1:3])
assert len(en) == len(it), 'the two files must have the same length'
for a, b in zip(en, it):
    assert a[0] == b[0] and len(a) == len(b) == 6 and all(isinstance(x, str) and x.strip() for x in a[1:] + b[1:]), (a, b)
for lang, data in (('en', en), ('it', it)):
    head = '// Botola questions (%s), generated by tools/build-botola-q.py. Source: Open Trivia DB (opentdb.com), CC BY-SA 4.0.\n' % lang
    open('public/js/botola-q-%s.js' % lang, 'w').write(head + 'window.BotolaQ_%s = %s;\n' % (lang, json.dumps(data, ensure_ascii=False, separators=(',', ':'))))
print(len(en), 'questions')
